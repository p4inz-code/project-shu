import fs from 'node:fs';
import path from 'node:path';

const rootDir = process.cwd();
const photosDir = path.join(rootDir, 'private-content', 'photos');
const audioDir = path.join(rootDir, 'private-content', 'audio');
const videoDir = path.join(rootDir, 'private-content', 'video');
const outDir = path.join(rootDir, 'functions', '_generated');

fs.mkdirSync(outDir, { recursive: true });

const MIME_MAP = {
  '.svg': 'image/svg+xml; charset=utf-8',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
  '.webp': 'image/webp',
  '.avif': 'image/avif',
  '.gif': 'image/gif',
  '.mp3': 'audio/mpeg',
  '.wav': 'audio/wav',
  '.ogg': 'audio/ogg',
  '.m4a': 'audio/mp4',
  '.mp4': 'video/mp4',
  '.webm': 'video/webm',
  '.mov': 'video/quicktime',
};

// Priority order when resolving by stem (so dropping memory-01.jpg overrides memory-01.svg automatically!)
const PHOTO_EXT_PRIORITY = [
  '.jpg',
  '.jpeg',
  '.png',
  '.webp',
  '.avif',
  '.gif',
  '.svg',
];
const AUDIO_EXT_PRIORITY = ['.mp3', '.m4a', '.ogg', '.wav'];
const VIDEO_EXT_PRIORITY = ['.mp4', '.webm', '.mov', '.svg'];

function collectAssets(dirPath, priorityList) {
  if (!fs.existsSync(dirPath)) return { byStem: {}, byFilename: {} };
  const files = fs.readdirSync(dirPath).filter((f) => !f.startsWith('.'));
  const byStem = {};
  const byFilename = {};

  for (const file of files) {
    const ext = path.extname(file).toLowerCase();
    const mimeType = MIME_MAP[ext];
    if (!mimeType) continue;
    const stem = path.basename(file, path.extname(file));
    const buf = fs.readFileSync(path.join(dirPath, file));
    const entry = {
      filename: file,
      mimeType,
      base64: buf.toString('base64'),
      size: buf.length,
      ext,
    };
    byFilename[file] = entry;

    const existing = byStem[stem];
    if (!existing) {
      byStem[stem] = entry;
    } else {
      const existingRank = priorityList.indexOf(existing.ext);
      const newRank = priorityList.indexOf(ext);
      if (newRank !== -1 && (existingRank === -1 || newRank < existingRank)) {
        byStem[stem] = entry;
      }
    }
  }

  return { byStem, byFilename };
}

const photos = collectAssets(photosDir, PHOTO_EXT_PRIORITY);
const audio = collectAssets(audioDir, AUDIO_EXT_PRIORITY);
const video = collectAssets(videoDir, VIDEO_EXT_PRIORITY);

const outputTs = `// AUTO-GENERATED BY scripts/pack-private-assets.mjs — DO NOT EDIT MANUALLY
export interface PackedAsset {
  filename: string;
  mimeType: string;
  base64: string;
  size: number;
  ext: string;
}

export const PACKED_PHOTOS_BY_STEM: Record<string, PackedAsset> = ${JSON.stringify(photos.byStem, null, 2)};
export const PACKED_PHOTOS_BY_FILENAME: Record<string, PackedAsset> = ${JSON.stringify(photos.byFilename, null, 2)};
export const PACKED_AUDIO_BY_STEM: Record<string, PackedAsset> = ${JSON.stringify(audio.byStem, null, 2)};
export const PACKED_AUDIO_BY_FILENAME: Record<string, PackedAsset> = ${JSON.stringify(audio.byFilename, null, 2)};
export const PACKED_VIDEO_BY_STEM: Record<string, PackedAsset> = ${JSON.stringify(video.byStem, null, 2)};
export const PACKED_VIDEO_BY_FILENAME: Record<string, PackedAsset> = ${JSON.stringify(video.byFilename, null, 2)};
`;

fs.writeFileSync(path.join(outDir, 'private-bundle.ts'), outputTs, 'utf8');
console.log(
  `Packed ${Object.keys(photos.byStem || {}).length} private photo stems, ${Object.keys(audio.byStem || {}).length} private audio stems, and ${Object.keys(video.byStem || {}).length} private video stems into functions/_generated/private-bundle.ts.`,
);
